def write_readme(path: Path, summary: dict[str, Any]) -> None:
    lines = [
        "# SO-101 Source Authority Matrix",
        "",
        f"- `status`: `{summary['status']}`",
        f"- `case_count`: `{summary['case_count']}`",
        f"- `failed_cases`: `{', '.join(summary['failed_case_ids']) if summary['failed_case_ids'] else 'none'}`",
        f"- `summary_json`: `{summary['artifacts']['summary_json']}`",
        f"- `cases_csv`: `{summary['artifacts']['cases_csv']}`",
        "",
        "Synthetic fixture caveat: these generated URDFs are automation fixtures only. They are not reviewed physical SO-101 model authority.",
        "",
        "## Cases",
        "",
        "| Case | Status | Candidates | Authoritative | Source Gate | Review Status | Intake | Actions | Summary |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for case in summary["cases"]:
        observations = case["observations"]
        lines.append(
            "| `{case_id}` | `{status}` | `{candidates}` | `{authoritative}` | `{gate}` | `{review}` | `{intake}` | `{actions}` | `{summary_path}` |".format(
                case_id=case["case_id"],
                status=case["status"],
                candidates=observations.get("candidate_count"),
                authoritative=observations.get("authoritative_candidate_count"),
                gate=observations.get("source_authority_gate_status"),
                review=observations.get("source_authority_review_status"),
                intake=observations.get("source_intake_status"),
                actions=", ".join(observations.get("next_required_action_ids") or []),
                summary_path=case["summary_path"],
            )
        )
    lines.extend(
        [
            "",
            "## Caveats",
            "",
            "- Source-authority-ready fixture cases still report source-intake and review-packet artifacts as not authority.",
            "- Physical SO-101 model authority remains false in every case.",
            "- A reviewed bundle manifest with mesh roots, joint limits, target frame, TCP offset, and base-to-board alignment is still required before model-backed work is trusted.",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main() -> int:
    args = parse_args()
    output_dir = normalize_path(args.output_dir)
    if output_dir.exists() and not args.keep_existing:
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    fixtures = create_fixtures(output_dir)
    cases: list[dict[str, Any]] = []
    for spec in case_specs(fixtures):
        record, inventory = run_case(
            case_id=spec["case_id"],
            case_args=spec["args"],
            python_path=args.python,
            output_dir=output_dir,
        )
        cases.append(summarize_case(record, inventory, spec["expect"]))

    ok = all(case["ok"] for case in cases)
    summary_path = output_dir / "so101_source_authority_matrix_summary.json"
    csv_path = output_dir / "so101_source_authority_matrix_cases.csv"
    readme_path = output_dir / "README.md"
    summary = {
        "schema": SCHEMA,
        "ok": ok,
        "status": "ok" if ok else "validation_failed",
        "repo_root": str(REPO_ROOT),
        "output_dir": str(output_dir),
        "hardware_skipped": True,
        "gui_skipped": True,
        "openai_skipped": True,
        "case_count": len(cases),
        "case_ids": [case["case_id"] for case in cases],
        "failed_case_ids": [case["case_id"] for case in cases if not case["ok"]],
        "fixtures": {key: str(normalize_path(value)) for key, value in fixtures.items()},
        "cases": cases,
        "artifacts": {
            "summary_json": str(summary_path),
            "cases_csv": str(csv_path),
            "readme_md": str(readme_path),
        },
        "limitations": [
            "Synthetic URDF fixtures live under the smoke output directory and are not physical SO-101 calibration truth.",
            "The source-authority-ready case proves the inventory state transition only; it does not supply a reviewed bundle manifest.",
            "This smoke does not open robot hardware, cameras, GUI flows, network resources, or LLM/OpenAI paths.",
        ],
    }
    write_json(summary_path, summary)
    write_csv(csv_path, [flatten_case(case) for case in cases])
    write_readme(readme_path, summary)

    print(
        json.dumps(
            {
                "ok": ok,
                "status": summary["status"],
                "summary_json": str(summary_path),
                "cases_csv": str(csv_path),
                "readme_md": str(readme_path),
                "case_ids": summary["case_ids"],
                "failed_cases": summary["failed_case_ids"],
            },
            sort_keys=True,
        )
    )
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
